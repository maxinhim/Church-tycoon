    if(S.week-c.w<CARE_DUE)return true;
    careHit(a,-2,CARE_LEAVE);if(b)careHit(b,-1);S.tempMood-=CARE_IGNORE_MOOD;
    addLog(CARES[c.k].t+' · 돌보지 못해 마음이 멀어졌어요');return false;
